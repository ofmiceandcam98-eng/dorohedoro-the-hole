package com.dorohedoro.hole.client.ui;

import com.dorohedoro.hole.Dorohedoro;
import com.dorohedoro.hole.client.magic.SmokeClient;
import com.dorohedoro.hole.magic.SmokeSkill;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.Font;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.gui.components.PlayerFaceRenderer;
import net.minecraft.client.player.LocalPlayer;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.effect.MobEffects;

/**
 * The status plate in the top-left corner and the experience gauge over the hotbar.
 *
 * <p>Your face in a riveted iron frame, then framed bars with the numbers inside: blood for health, gyoza for hunger,
 * smoke for a sorcerer's reserve and air while underwater. Status effects recolour the health bar, absorption is a
 * gold band over it, saturation is a pale line under hunger, and recent damage leaves a pale chunk that drains away.
 * The Z/X/C technique sockets sit below. All art is original, generated by {@code tools/ui/gen-ui.mjs}.
 */
public final class HoleHud {
    private static final int BAR_W = 96, BAR_H = 9, FRAME_W = 100, FRAME_H = 13, ROW = 14;

    private static final ResourceLocation PORTRAIT = sprite("hud/portrait_frame");
    private static final ResourceLocation BAR_FRAME = sprite("hud/bar_frame");
    private static final ResourceLocation XP_FRAME = sprite("hud/xp_frame");
    private static final ResourceLocation XP_FILL = sprite("hud/fill_xp");
    private static final ResourceLocation LEVEL_PLATE = sprite("hud/level_plate");
    private static final ResourceLocation SLOT = sprite("hud/slot");
    private static final ResourceLocation SLOT_FOCUSED = sprite("hud/slot_focused");
    private static final ResourceLocation KEY_PLATE = sprite("hud/key_plate");
    private static final ResourceLocation CHIP = sprite("hud/chip");
    private static final ResourceLocation GHOST = sprite("hud/fill_ghost");
    private static final ResourceLocation ABSORB = sprite("hud/fill_absorb");

    private static float ghostHealth = -1;
    private static long ghostHoldUntil;
    private static long lastFrameNanos;

    private HoleHud() {}

    private static ResourceLocation sprite(String path) {
        return ResourceLocation.fromNamespaceAndPath(Dorohedoro.MOD_ID, path);
    }

    /** True when this HUD replaces vanilla hearts, food, armor and air: survival and adventure only. */
    public static boolean replacesVanillaStats(Minecraft mc) {
        return mc.player != null && mc.gameMode != null && mc.gameMode.canHurtPlayer() && !mc.options.hideGui;
    }

    /** True when the experience gauge replaces vanilla's bar: same modes, and not while steering a jumping mount. */
    public static boolean replacesVanillaExperience(Minecraft mc) {
        return replacesVanillaStats(mc) && mc.player.jumpableVehicle() == null;
    }

    public static void render(GuiGraphics g) {
        Minecraft mc = Minecraft.getInstance();
        LocalPlayer player = mc.player;
        if (player == null || mc.screen != null || mc.options.hideGui || player.isSpectator()) return;
        Font font = mc.font;
        boolean stats = replacesVanillaStats(mc);
        boolean sorcerer = !"none".equals(SmokeClient.innate);
        boolean underwater = player.getAirSupply() < player.getMaxAirSupply();

        int x = 4, y = 4;
        int rows = (stats ? 2 : 0) + (sorcerer ? 1 : 0) + (stats && underwater ? 1 : 0);
        int below = y;
        if (rows > 0) {
            g.blitSprite(PORTRAIT, x, y, 42, 42);
            PlayerFaceRenderer.draw(g, player.getSkin(), x + 5, y + 5, 32);
            if (sorcerer) g.blitSprite(sprite("hud/icon_smoke"), x + 31, y + 31, 9, 9);
            int bx = x + 46, by = y + 1;
            if (stats) {
                health(g, font, player, bx, by);
                by += ROW;
                hunger(g, font, player, bx, by);
                by += ROW;
            }
            if (sorcerer) {
                bar(g, font, "smoke", "fill_smoke", SmokeClient.smoke, SmokeClient.maxSmoke, bx, by, null);
                by += ROW;
            }
            if (stats && underwater) {
                int air = Math.max(0, player.getAirSupply());
                bar(g, font, "air", "fill_air", air * 100f / player.getMaxAirSupply(), 100, bx, by, "%");
                by += ROW;
            }
            below = Math.max(y + 44, by + 1);
        }

        // Chips under the portrait: armor and an untreated injury.
        int cx = x;
        if (stats && player.getArmorValue() > 0) {
            chip(g, font, "armor", Integer.toString(player.getArmorValue()), cx, below);
            cx += 32;
        }
        if (!"none".equals(SmokeClient.injury)) {
            chip(g, font, "injury", "!", cx, below);
            cx += 32;
        }
        if (cx > x) below += 13;

        if (sorcerer) slots(g, font, x, below + 2);
        if (replacesVanillaExperience(mc)) experience(g, font, player, mc.getWindow().getGuiScaledWidth(),
                mc.getWindow().getGuiScaledHeight());
    }

    private static void health(GuiGraphics g, Font font, LocalPlayer player, int x, int y) {
        float health = player.getHealth(), max = player.getMaxHealth();
        String fill = player.hasEffect(MobEffects.WITHER) ? "fill_wither"
                : player.hasEffect(MobEffects.POISON) ? "fill_poison"
                : player.isFullyFrozen() || player.getTicksFrozen() > 0 ? "fill_frozen" : "fill_health";
        // Damage ghost: holds for a moment after a hit, then drains to the real value.
        long now = System.nanoTime();
        float dt = lastFrameNanos == 0 ? 0 : Math.min(0.1f, (now - lastFrameNanos) / 1e9f);
        lastFrameNanos = now;
        if (ghostHealth < health || ghostHealth < 0) {
            ghostHealth = health;
        } else if (ghostHealth > health) {
            if (ghostHoldUntil == 0) ghostHoldUntil = now + 450_000_000L;
            if (now > ghostHoldUntil) ghostHealth = Math.max(health, ghostHealth - max * 0.9f * dt);
        }
        if (ghostHealth <= health) ghostHoldUntil = 0;

        icon(g, "health", x, y);
        int fx = x + 13, fy = y + 2;
        g.blitSprite(BAR_FRAME, x + 11, y, FRAME_W, FRAME_H);
        int ghostW = width(ghostHealth, max);
        if (ghostW > 0) g.blitSprite(GHOST, BAR_W, BAR_H, 0, 0, fx, fy, ghostW, BAR_H);
        int w = width(health, max);
        if (w > 0) g.blitSprite(sprite("hud/" + fill), BAR_W, BAR_H, 0, 0, fx, fy, w, BAR_H);
        float absorb = player.getAbsorptionAmount();
        if (absorb > 0) {
            // Absorption is a gold band along the top of the bar, sized against max health.
            g.blitSprite(ABSORB, BAR_W, BAR_H, 0, 0, fx, fy, width(Math.min(absorb, max), max), 3);
        }
        // Below a quarter health the frame pulses red.
        if (health <= max / 4 && (player.tickCount / 6) % 2 == 0) {
            g.fill(x + 11, y, x + 11 + FRAME_W, y + 1, 0xFFE2473C);
            g.fill(x + 11, y + FRAME_H - 1, x + 11 + FRAME_W, y + FRAME_H, 0xFFE2473C);
        }
        String text = Mth.ceil(health) + (absorb > 0 ? "+" + Mth.ceil(absorb) : "") + " / " + Mth.ceil(max);
        number(g, font, text, fx, fy);
    }

    private static void hunger(GuiGraphics g, Font font, LocalPlayer player, int x, int y) {
        var food = player.getFoodData();
        String fill = player.hasEffect(MobEffects.HUNGER) ? "fill_poison" : "fill_hunger";
        bar(g, font, "hunger", fill, food.getFoodLevel(), 20, x, y, null);
        // Saturation: a pale line along the bottom of the channel, like a full belly's reserve.
        int sat = width(food.getSaturationLevel(), 20);
        if (sat > 0) g.fill(x + 13, y + 2 + BAR_H - 1, x + 13 + sat, y + 2 + BAR_H, 0xC0FFF0C8);
    }

    private static void bar(GuiGraphics g, Font font, String icon, String fill, float value, float max, int x, int y,
            String suffix) {
        icon(g, icon, x, y);
        g.blitSprite(BAR_FRAME, x + 11, y, FRAME_W, FRAME_H);
        int w = width(value, max);
        if (w > 0) g.blitSprite(sprite("hud/" + fill), BAR_W, BAR_H, 0, 0, x + 13, y + 2, w, BAR_H);
        String text = suffix != null ? Mth.ceil(value) + suffix : Mth.ceil(value) + " / " + Mth.ceil(max);
        number(g, font, text, x + 13, y + 2);
    }

    private static void icon(GuiGraphics g, String name, int x, int y) {
        g.blitSprite(sprite("hud/icon_" + name), x, y + 2, 9, 9);
    }

    private static int width(float value, float max) {
        return Math.round(BAR_W * Mth.clamp(value / Math.max(1f, max), 0f, 1f));
    }

    /** Centred numbers inside a bar channel, with a shadow so they read on any fill. */
    private static void number(GuiGraphics g, Font font, String text, int fx, int fy) {
        int tx = fx + (BAR_W - font.width(text)) / 2;
        g.drawString(font, text, tx, fy + 1, 0xFFF4EEE2, true);
    }

    private static void chip(GuiGraphics g, Font font, String icon, String text, int x, int y) {
        g.blitSprite(CHIP, x, y, 30, 11);
        g.blitSprite(sprite("hud/icon_" + icon), x + 2, y + 1, 9, 9);
        g.drawString(font, text, x + 13, y + 2, icon.equals("injury") ? 0xFFF2A77C : 0xFFE6E9E3, true);
    }

    private static void slots(GuiGraphics g, Font font, int x, int y) {
        for (int i = 0; i < 3; i++) {
            int sy = y + i * 29;
            g.blitSprite(SmokeClient.focused(i) ? SLOT_FOCUSED : SLOT, x, sy, 26, 26);
            SmokeSkill skill = SmokeSkill.fromId(SmokeClient.slot(i));
            if (skill != null) {
                SmokeSkillIcon.draw(g, skill, x + 3, sy + 3, 20);
                int cooldown = SmokeClient.cooldown(i);
                if (cooldown > 0) {
                    // Cooldown drains from the top, like smoke clearing out of the socket.
                    float left = Mth.clamp(cooldown / (float) Math.max(1, skill.cooldownTicks()), 0f, 1f);
                    int h = Math.round(20 * left);
                    g.fill(x + 3, sy + 3 + (20 - h), x + 23, sy + 23, 0xB0091116);
                    String seconds = Integer.toString((cooldown + 19) / 20);
                    g.drawString(font, seconds, x + 13 - font.width(seconds) / 2, sy + 9, 0xFFFFFFFF, true);
                }
            } else {
                g.drawString(font, "-", x + 11, sy + 9, 0xFF8D9B99, true);
            }
            g.blitSprite(KEY_PLATE, x + 28, sy + 7, 12, 12);
            String key = SmokeClient.keyLabel(i);
            g.drawString(font, key, x + 34 - font.width(key) / 2, sy + 9, 0xFFE6E9E3, true);
        }
    }

    private static void experience(GuiGraphics g, Font font, LocalPlayer player, int screenW, int screenH) {
        int x = (screenW - 184) / 2, y = screenH - 30;
        g.blitSprite(XP_FRAME, x, y, 184, 9);
        int w = Math.round(180 * Mth.clamp(player.experienceProgress, 0f, 1f));
        if (w > 0) g.blitSprite(XP_FILL, 180, 5, 0, 0, x + 2, y + 2, w, 5);
        if (player.experienceLevel > 0) {
            String level = Integer.toString(player.experienceLevel);
            int pw = Math.max(26, font.width(level) + 10);
            int px = (screenW - pw) / 2;
            g.blitSprite(LEVEL_PLATE, px, y - 11, pw, 13);
            g.drawString(font, level, (screenW - font.width(level)) / 2, y - 8, 0xFFB9EA58, true);
        }
    }
}
